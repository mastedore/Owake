constexpr char endline = 0x0b;
constexpr char pause = 0x0a;
constexpr char stop = 0x0c;

// Lives in flash so it doesn't take ~190 bytes of stack. Bytes 0x00-0x07
// are the custom glyphs loaded by defineFont(0), and the three control
// bytes above drive typeEffect().
