// text must point to flash (PROGMEM).
static void typeEffect(const char *text)
{
	uint8_t col = 0, row = 0;
	uint8_t textIndex = 0;

	char c;
	while ((c = static_cast<char>(pgm_read_byte(&text[textIndex++]))) != stop)
	{
		wdt_reset();

		if (c == endline)
		{
			row++;
			col = 0;
			lcd.writePosition(col, row);
		}
		else if (c == pause)
		{
			delay(1500);
			// Erase backwards, one cell at a time, like a backspace.
			while (col > 0 || row > 0)
			{
				wdt_reset();
				if (col > 0)
				{
					col--;
				}
				else if (row > 0)
				{
					row--;
					col = COLS - 1;
				}

				lcd.writePosition(col, row);
				lcd.writeChar(' ');
				delay(66);
			}
		}
		else
		{
			lcd.writePosition(col, row);
			lcd.writeChar(static_cast<uint8_t>(c));
			col++;
			delay(84);
		}
	}

	delay(2000);

	lcd.writePosition(0, 0);
}

void Credits::Main::setup(StateCtx *ctx)
{
	defineFont(0);
	lcd.cursor(true);
	lcd.blink(true);
}

void Credits::Main::loop(StateCtx *ctx)
{
	delay(2000);
	lcd.blink(true);
	lcd.cursor(true);

	typeEffect(opcodes);

	ctx->self->sys->requestShiftSubsystem(OwakeSubsystemID::MENU);
	return;
}

void Credits::Main::exit(StateCtx *ctx)
{
}
